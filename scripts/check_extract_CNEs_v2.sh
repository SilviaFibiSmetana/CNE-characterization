#!/bin/bash

[[ -d "$CNEOUTPUTDIR" ]] || error_exit "$LINENO" "Cannot find $CNEOUTPUTDIR!"
[[ -f "$PHASTCONSELEMENTSFILEBB" ]] || error_exit "$LINENO" "Cannot find $PHASTCONSELEMENTSFILEBB!"

TARGETDISTANCE=50
PHASTCONFRACTION=0.5

# FILE PREFIX

if [[ -z "${PHASTCONSELEMENTSFILENAME:-}" ]]; then
	error_exit "$LINENO" "$PHASTCONSELEMENTSFILENAME is undefined or empty."
fi

# MAIN OUTPUT FILE

if [[ -z "${PHASTCONSELEMENTSSELECTEDLENGTHFILE:-}" ]]; then
	error_exit "$LINENO" "$PHASTCONSELEMENTSSELECTEDLENGTHFILE is undefined or empty."
fi

# GET LENGTH OF CONSERVED ELEMENTS (CEs)

PHASTCONSELEMENTSFILE="${CNEOUTPUTDIR}/${PHASTCONSELEMENTSFILENAME}.txt"

bigBedToBed "$PHASTCONSELEMENTSFILEBB" "$PHASTCONSELEMENTSFILE"
head "$PHASTCONSELEMENTSFILE"
wc -l "$PHASTCONSELEMENTSFILE"

# ONE COL HAS TO BE ADDED THAT ALL THE FOLLOWUP SCRIPTS WONT WORK

PHASTCONSELEMENTSLENGTHFILE="${CNEOUTPUTDIR}/${PHASTCONSELEMENTSFILENAME%%.*}_incl_CElength.txt"

cat "$PHASTCONSELEMENTSFILE" | awk '{print 585"\t"$0}' | awk '{ print $0"\t"$4-$3 }' > "$PHASTCONSELEMENTSLENGTHFILE" 
head "$PHASTCONSELEMENTSLENGTHFILE"
wc -l "$PHASTCONSELEMENTSLENGTHFILE"

echo

# GET RID OF PHASTCONSELEMENTS, WHICH ARE NOT IN A STANDARD CHROMOSOME

PHASTCONSELEMENTSCORRECTCHROMOSOMESFILE="${CNEOUTPUTDIR}/${PHASTCONSELEMENTSFILENAME}_correct_chromosomes.txt"

cat "$PHASTCONSELEMENTSFILE" | grep -v "_" > "$PHASTCONSELEMENTSCORRECTCHROMOSOMESFILE"
head "$PHASTCONSELEMENTSCORRECTCHROMOSOMESFILE"
wc -l "$PHASTCONSELEMENTSCORRECTCHROMOSOMESFILE"

echo

# MERGE ELEMENTS IF THE MERGED ONE HAS A PHASTCON CONTENT HIGHER 50% IF THE DISTANCE WITHIN IS SMALLER 50 BP

PHASTCONSELEMENTSSELECTEDCOLUMNSFILE="${CNEOUTPUTDIR}/${PHASTCONSELEMENTSFILENAME}_selected_columns.txt"
PHASTCONSELEMENTSMERGEDFILE="${CNEOUTPUTDIR}/${PHASTCONSELEMENTSFILENAME}_merged.txt"

# select only the chr start and end columns
awk -F"\t" 'BEGIN {OFS = FS} {print $1,$2,$3}' "$PHASTCONSELEMENTSCORRECTCHROMOSOMESFILE" > "$PHASTCONSELEMENTSSELECTEDCOLUMNSFILE"
head "$PHASTCONSELEMENTSSELECTEDCOLUMNSFILE"
wc -l "$PHASTCONSELEMENTSSELECTEDCOLUMNSFILE"

echo 

# APPLY A PERL SCRIPT THAT TAKES NEIGBORING CNES IN CLOSE PROXIMITY, LESS THAN 50 BP, AND STARTS MERGING FROM THE ONES WITH THE SMALLEST DISTANCE WHEN THE PHASTCON CONTENT IS GREATER THAN 33% AND GOES ON UNTIL EVERY NEIGHBORING PAIR IS CHECKED AND THEN JUMPS TO THE NEXT BUNCH OF ELEMENTS IN CLOSE PROXIMITY
perl "${SCRIPTS}/merge_phastcons_condition_v2.pl" "$TARGETDISTANCE" "$PHASTCONFRACTION" "$PHASTCONSELEMENTSSELECTEDCOLUMNSFILE" "$PHASTCONSELEMENTSMERGEDFILE"
head "$PHASTCONSELEMENTSMERGEDFILE"
wc -l "$PHASTCONSELEMENTSMERGEDFILE"

# FILTER FOR ELEMENTS LONGER THAN 50 NUCLEOTIDES
cat "$PHASTCONSELEMENTSMERGEDFILE" | awk '{print $1"\t"$2"\t"$3"\t"$3-$2}' | awk '{ if(($4 > 50)) { print $0 } }' > "$PHASTCONSELEMENTSSELECTEDLENGTHFILE"

echo "# Conserved elements are stored in $PHASTCONSELEMENTSSELECTEDLENGTHFILE"
head "$PHASTCONSELEMENTSSELECTEDLENGTHFILE"
wc -l "$PHASTCONSELEMENTSSELECTEDLENGTHFILE"

echo "Done!"
